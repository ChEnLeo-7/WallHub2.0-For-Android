#!/usr/bin/env node

import {readFile, writeFile} from 'node:fs/promises';

const contractPath = 'shared/ui-contract/wallhub-current.json';
const cssPath = 'preview/web-dom/src/contract.css';
const sharedTokensPath = 'shared/ui/src/commonMain/kotlin/com/wallhub/shared/ui/WallHubDesignTokens.kt';
const androidTokensPath = 'app/src/main/kotlin/com/wallhub/android/core/designsystem/WallHubDesignTokens.kt';
const windowClassPath = 'shared/ui/src/commonMain/kotlin/com/wallhub/shared/ui/WallHubWindowSizeClass.kt';
const androidThemePath = 'app/src/main/kotlin/com/wallhub/android/core/designsystem/WallHubTheme.kt';
const androidDestinationsPath = 'app/src/main/kotlin/com/wallhub/android/navigation/TopLevelDestinations.kt';
const androidChineseStringsPath = 'app/src/main/res/values-zh-rCN/strings.xml';
const contract = JSON.parse(await readFile(contractPath, 'utf8'));
const kebabCase = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
const themeVariables = (theme) => Object.entries(theme)
  .map(([name, value]) => `  --md-sys-color-${kebabCase(name)}: ${value};`)
  .join('\n');
const css = `/* Generated by scripts/sync-web-ui-contract.mjs. Do not edit. */
:root {
${themeVariables(contract.themes.dark)}
  --wallhub-canvas: ${contract.themes.dark.background};
  --wallhub-focus: ${contract.themes.dark.primary};
  --wallhub-nav-width: ${contract.sizes.mediumNavigationRailWidth}px;
  --wallhub-drawer-width: ${contract.sizes.expandedNavigationDrawerWidth}px;
  --wallhub-content-max: ${contract.sizes.readableContentMaxWidth}px;
  --wallhub-space-1: ${contract.spacing.xs}px;
  --wallhub-space-2: ${contract.spacing.md}px;
  --wallhub-space-3: ${contract.spacing.lg}px;
  --wallhub-shape-medium: ${contract.shapes.medium}px;
}
:root[data-theme='light'] {
${themeVariables(contract.themes.light)}
  --wallhub-canvas: ${contract.themes.light.background};
  --wallhub-focus: ${contract.themes.light.primary};
}
`;

function requireText(source, text, label) {
  if (!source.includes(text)) throw new Error(`${label} is missing ${JSON.stringify(text)}`);
}

for (const path of [sharedTokensPath, androidTokensPath]) {
  const source = await readFile(path, 'utf8');
  for (const [name, value] of Object.entries(contract.spacing)) {
    requireText(source, `val ${name}: Dp = ${value}.dp`, path);
  }
  for (const [name, value] of Object.entries(contract.shapes)) {
    requireText(source, `val ${name} = RoundedCornerShape(${value}.dp)`, path);
  }
  for (const [name, value] of Object.entries(contract.sizes)) {
    if (name === 'mediumNavigationRailWidth') continue;
    requireText(source, `val ${name}: Dp = ${value}.dp`, path);
  }
}
const windowClass = await readFile(windowClassPath, 'utf8');
requireText(windowClass, `widthDp < ${contract.breakpoints.medium}f`, windowClassPath);
requireText(windowClass, `widthDp < ${contract.breakpoints.expanded}f`, windowClassPath);
const sharedTokens = await readFile(sharedTokensPath, 'utf8');
const darkBlock = sharedTokens.split('darkColorScheme(', 2)[1].split(')\n    } else', 1)[0];
const lightBlock = sharedTokens.split('lightColorScheme(', 2)[1].split('\n        )', 1)[0];
for (const [themeName, theme] of Object.entries(contract.themes)) {
  const block = themeName === 'dark' ? darkBlock : lightBlock;
  for (const [name, value] of Object.entries(theme)) {
    const color = value.slice(1).toUpperCase();
    const expression = color === 'FFFFFF' ? 'Color.White' : `Color(0xFF${color})`;
    requireText(block, `${name} = ${expression}`, `${sharedTokensPath} ${themeName}`);
  }
}

const androidTheme = await readFile(androidThemePath, 'utf8');
const androidConstants = new Map([
  ['Color.White', '#ffffff'],
  ['Color.Black', '#000000'],
]);
for (const match of androidTheme.matchAll(/private val ([A-Z0-9_]+) = Color\(0xFF([A-F0-9]{6})\)/g)) {
  androidConstants.set(match[1], `#${match[2].toLowerCase()}`);
}
const androidDarkBlock = androidTheme.split('darkColorScheme(', 2)[1].split(')\n    } else', 1)[0];
const androidLightBlock = androidTheme.split('lightColorScheme(', 2)[1].split('\n        )', 1)[0];
for (const [themeName, theme] of Object.entries(contract.themes)) {
  const block = themeName === 'dark' ? androidDarkBlock : androidLightBlock;
  for (const [name, expected] of Object.entries(theme)) {
    const assignment = block.match(new RegExp(`${name}\\s*=\\s*([A-Za-z0-9_.]+)`));
    if (!assignment) throw new Error(`${androidThemePath} ${themeName} is missing ${name}`);
    const actual = androidConstants.get(assignment[1]);
    if (actual !== expected) {
      throw new Error(`${androidThemePath} ${themeName}.${name}: ${actual} != ${expected}`);
    }
  }
}

const androidDestinations = await readFile(androidDestinationsPath, 'utf8');
const androidChineseStrings = await readFile(androidChineseStringsPath, 'utf8');
const androidRows = [...androidDestinations.matchAll(/^\s+([A-Z]+)\(([^)]+)\),$/gm)].map((match) => ({
  entry: match[1],
  values: match[2].split(',').map((value) => value.trim()),
}));
if (androidRows.length !== contract.destinations.length) {
  throw new Error(`${androidDestinationsPath} has ${androidRows.length} entries, expected ${contract.destinations.length}`);
}
contract.destinations.forEach((destination, index) => {
  const row = androidRows[index];
  const expected = [
    destination.androidTarget,
    `R.string.${destination.androidLabelResource}`,
    destination.androidIcon,
    destination.androidSelectedIcon,
  ];
  if (row.entry !== destination.androidEntry || JSON.stringify(row.values) !== JSON.stringify(expected)) {
    throw new Error(`${androidDestinationsPath} row ${index}: ${row.entry}(${row.values}) != ${destination.androidEntry}(${expected})`);
  }
  const escaped = destination.androidLabelResource.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = androidChineseStrings.match(new RegExp(`<string name=['"]${escaped}['"]>([^<]+)</string>`));
  if (!match || match[1] !== destination.label) {
    throw new Error(`${androidChineseStringsPath} ${destination.androidLabelResource}: ${match?.[1]} != ${destination.label}`);
  }
});

if (process.argv.includes('--write')) {
  await writeFile(cssPath, css);
  console.log(`UI_CONTRACT_SYNC=OK wrote=${cssPath}`);
} else {
  const existing = await readFile(cssPath, 'utf8').catch(() => '');
  if (existing !== css) throw new Error(`${cssPath} is stale; run scripts/sync-web-ui-contract.mjs --write`);
  console.log('UI_CONTRACT_CHECK=OK android=parity shared=parity web=generated');
}
